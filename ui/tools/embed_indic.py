"""Reproduce the immutable OFL font arrays from the pinned canary assets."""
from pathlib import Path
import hashlib
import sys

# The font folder comes from indic_fonts.mk (its place differs between the dev and the public tree).
app = Path(__file__).resolve().parents[1]
fonts = Path(sys.argv[1]) if len(sys.argv) > 1 else app.parents[1] / 'tools/hbcanary/fonts'
output = app / 'indic_fonts.inc'
names = ['NotoSansGurmukhiUI-SemiBold.ttf', 'NotoSansDevanagari-SemiBold.ttf',
         'NotoNaskhArabic-SemiBold.ttf', 'NotoSansHebrew-SemiBold.ttf']
with output.open('w', encoding='ascii') as f:
    f.write('/* Generated by tools/embed_indic.py; font data is OFL-1.1. */\n')
    for i, name in enumerate(names):
        data = (fonts / name).read_bytes()
        f.write(f'/* {name}: SHA256 {hashlib.sha256(data).hexdigest()} */\n')
        f.write(f'static const unsigned char indic_font_{i}[] = {{\n')
        for start in range(0, len(data), 24):
            f.write(','.join(str(b) for b in data[start:start + 24]) + ',\n')
        f.write('};\n')
